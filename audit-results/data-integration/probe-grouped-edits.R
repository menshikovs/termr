pkgload::load_all(".", quiet = TRUE)
input <- tibble::tibble(group = c("a", "b", "a"), value = 1:3)
grouped <- dplyr::group_by(input, group)
tab <- data_table(grouped, editable = TRUE)
cat("before:\n"); print(dplyr::group_data(tab$data))
tab$set_cell(1L, "group", "b")
cat("after values:\n"); print(tab$data)
cat("after groups:\n"); print(dplyr::group_data(tab$data))
rowwise <- dplyr::rowwise(input)
rowtab <- data_table(rowwise, editable = TRUE)
rowtab$set_cell(1L, "value", "9")
cat("rowwise class:", paste(class(rowtab$data), collapse = "/"), "\n")
cat("rowwise groups:\n"); print(dplyr::group_data(rowtab$data))