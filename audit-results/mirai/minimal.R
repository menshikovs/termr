lib <- file.path("audit-results/mirai", paste0("minimal-", host))
dir.create(lib, recursive = TRUE, showWarnings = FALSE)
for (package in c("R6", "processx", "ps")) stopifnot(file.copy(find.package(package), lib, recursive = TRUE))
install.packages(".", lib = lib, repos = NULL, type = "source")
.libPaths(normalizePath(lib), include.site = FALSE)
library(termr)
stopifnot(!"mirai" %in% loadedNamespaces(), !"nanonext" %in% loadedNamespaces(), !"shiny" %in% loadedNamespaces())
stopifnot(!requireNamespace("mirai", quietly = TRUE))
