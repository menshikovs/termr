host <- if (.Platform$OS.type == "windows") "windows" else "wsl"
lib <- file.path("audit-results/nanonext", paste0("minimal-", host))
dir.create(lib, recursive = TRUE, showWarnings = FALSE)
install.packages(".", lib = lib, repos = NULL, type = "source")
.libPaths(c(normalizePath(lib), .libPaths()))
stopifnot(!requireNamespace("nanonext", quietly = TRUE))
library(termr)
x <- termr_stream("minimal")
x$emit(42)
stopifnot(identical(x$latest(), 42))
pilot <- test_app(app(label("Without nanonext")), 30, 5)
stopifnot(any(grepl("Without nanonext", pilot$screen_text(), fixed = TRUE)))
pilot$stop()
message <- tryCatch({termr_nano_publish(x); "missing error"}, error = conditionMessage)
stopifnot(grepl("Install optional package 'nanonext'", message, fixed = TRUE))
