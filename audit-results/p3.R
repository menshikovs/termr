suppressMessages(pkgload::load_all(".", quiet = TRUE))
mk <- function() app(vertical(label("hello"), id = "root"))
t0 <- Sys.time()
r <- tryCatch({setTimeLimit(elapsed = 10, transient = TRUE); p <- test_app(mk()); p$wait_until_exit(0.01, 1e-7)}, error=function(e) conditionMessage(e))
cat("tiny interval 1e-7:", r, "after", format(round(difftime(Sys.time(), t0, units="secs"),1)), "\n")
tryit <- function(l, e) cat(sprintf("%-40s %s\n", l, tryCatch({force(e);"ok"}, error=function(e) paste("ERROR:", conditionMessage(e)))))
tryit("exit() no value", {a3 <- mk(); a3$set_timeout(0.1, function(app) app$exit()); p <- test_app(a3); print(p$wait_until_exit(1))})
tryit("callback error", {a3 <- mk(); a3$set_timeout(0.1, function(app) stop("cb")); p <- test_app(a3); p$wait_until_exit(1)})
tryit("with worker", {a3 <- mk(); p <- test_app(a3); a3$run_worker(function() {Sys.sleep(0.3); 1}); a3$set_timeout(0.05, function(app) app$exit("w")); print(p$wait_until_exit(3))})
