suppressMessages(pkgload::load_all(".", quiet = TRUE))
build <- function(n) app(vertical(lapply(seq_len(n), function(i) horizontal(label(paste("row", i)), input(paste("v", i)), button("b"))), id = "root"))
a <- build(200); p <- test_app(a, 120, 40); a$query("Input")[[1]]$focus()
for (i in 1:5) p$press("a")
Rprof("audit-results/logs/keypress.prof", interval = 0.005)
for (i in 1:30) p$press(if (i %% 2) "a" else "backspace")
Rprof(NULL)
s <- summaryRprof("audit-results/logs/keypress.prof")
print(head(s$by.total, 18)); print(head(s$by.self, 12))
