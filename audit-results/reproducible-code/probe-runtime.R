x <- c(1 / 3, NA_real_, NaN, Inf, -Inf)
table <- data_table(data.frame(x = x), cursor = "cell")
table$move_cursor(row = 1L, column = "x")
result <- table$reproducible_code("value")
cat(result$code, "\n")
cat(sprintf("source %.17g generated %.17g\n", x[[1L]], eval(parse(text = result$code))[[1L]]))
