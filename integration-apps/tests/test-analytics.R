test_that('analytics terminal and converted data preserve source/missing semantics', {
  demo <- analytics_terminal()
  p <- termr::test_app(demo$app, width = 90, height = 28)
  on.exit({p$stop(); demo$close()}, add = TRUE)
  p$press('f2', 'alt+s')
  expect_identical(demo$model$state$source, 'beta')
  expect_equal(demo$table$data$cpu, demo$model$frame()$cpu)
  p$press('f4')
  expect_identical(demo$table$row_count, 0L)
  p$press('f4', 'f5')
  expect_true(is.na(tail(demo$table$data$cpu, 1L)))
  expect_true(is.na(tail(demo$table$data$ram, 1L)))
  expect_s3_class(demo$table$data$timestamp, 'POSIXct')
  p$resize(40, 15)
  expect_length(p$screen_text(), 15L)
})

test_that('Shiny uses one receiver and one Plotly widget per session', {
  skip_if_not_installed('shiny'); skip_if_not_installed('ggplot2'); skip_if_not_installed('plotly')
  demo <- analytics_dashboard()
  on.exit(demo$close(), add = TRUE)
  expect_identical(demo$model$stream$subscriber_count(), 1L)
  shiny::testServer(demo$server, {
    session$flushReact()
    first <- session$userData$frame()
    expect_equal(first$cpu, demo$model$frame()$cpu)
    expect_identical(demo$receiver$diagnostics()$sessions, 1L)
    output$live
    widgets <- demo$diagnostics()$widget_builds
    session$setInputs(next_sample = 1)
    session$flushReact()
    expect_gt(nrow(session$userData$frame()), nrow(first))
    expect_identical(demo$diagnostics()$widget_builds, widgets)
    session$setInputs(source = 1); session$flushReact()
    expect_identical(demo$model$state$source, 'beta')
    session$setInputs(empty = 1); session$flushReact()
    expect_identical(nrow(session$userData$frame()), 0L)
    session$setInputs(empty = 2, invalid = 1); session$flushReact()
    expect_true(is.na(tail(session$userData$frame()$cpu, 1L)))
    expect_match(output$source_status, 'Метрικές|Beta')
    expect_match(output$terminal, 'cpu')
  })
  expect_identical(demo$receiver$diagnostics()$sessions, 0L)
  expect_identical(demo$receiver$diagnostics()$observers, 1L) # suspended until owner close
  demo$close()
  expect_identical(demo$receiver$diagnostics()$observers, 0L)
  expect_true(demo$receiver$is_closed())
  expect_identical(demo$model$stream$subscriber_count(), 0L)
})
