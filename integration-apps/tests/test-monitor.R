test_that('distributed monitor runs actual tasks, failures, cancellation and sockets', {
  skip_if_not_installed('mirai'); skip_if_not_installed('nanonext')
  demo <- distributed_monitor(workers = 1L)
  p <- termr::test_app(demo$app, width = 100, height = 30)
  on.exit({p$stop(); demo$close()}, add = TRUE)
  p$press('n')
  wait_real(function() any(demo$model$rows()$status == 'completed'), step = function() p$advance(.05))
  expect_equal(demo$model$state$tasks[[1L]]$result()$chunks, 12L)
  p$press('e')
  wait_real(function() any(demo$model$rows()$status == 'failed'), step = function() p$advance(.05))
  expect_match(demo$model$rows()$error[[2L]], 'Controlled Phase E task failure')
  p$press('l', 'c')
  wait_real(function() any(demo$model$rows()$status == 'cancelled'), step = function() p$advance(.05))
  wait_real(function() !is.null(demo$model$remote()$latest()), step = function() p$advance(.05))
  expect_identical(demo$model$remote()$status()$state, 'live')
  expect_lte(length(demo$model$remote()$history()), 128L)
  old <- demo$model$remote()
  p$press('d', 'r')
  wait_real(function() !is.null(demo$model$remote()$latest()), step = function() p$advance(.05))
  expect_true(old$is_closed())
  expect_identical(old$subscriber_count(), 0L)
  expect_identical(demo$model$remote()$subscriber_count(), 1L)
  p$resize(42, 18)
  expect_length(p$screen_text(), 18L)
  p$stop(); demo$close()
  expect_true(demo$model$pool$is_closed())
  expect_identical(demo$model$pool$events$subscriber_count(), 0L)
})

test_that('cancel/completion races and active shutdown retain single terminal transitions', {
  skip_if_not_installed('mirai'); skip_if_not_installed('nanonext')
  before <- vapply(ps::ps_children(ps::ps_handle(), recursive = TRUE), ps::ps_pid, 0L)
  model <- distributed_model(workers = 1L)
  on.exit(model$close(), add = TRUE)
  for (i in 1:5) {
    task <- model$submit()
    task$cancel()
    wait_real(task$ready, step = function() model$poll())
    expect_true(task$status() %in% c('completed', 'cancelled'))
    id <- task$info()$task_id
    terminal <- Filter(function(e) identical(e$task_id, id) && e$event %in%
      c('task_completed', 'task_failed', 'task_cancelled', 'task_timed_out'), model$state$events)
    expect_length(terminal, 1L)
  }
  model$submit(slow = TRUE)
  owned <- ps::ps_children(ps::ps_handle(), recursive = TRUE)
  owned <- Filter(function(handle) !ps::ps_pid(handle) %in% before, owned)
  model$close()
  wait_real(function() !any(vapply(owned, ps::ps_is_running, TRUE)), timeout = 15)
  expect_true(model$pool$is_closed())
})

