monitor_demo <- function(script = "common.R") {
  env <- new.env(parent = globalenv())
  path <- system.file("examples", "system-monitor-live", script, package = "termr")
  if (!nzchar(path)) path <- test_path("..", "..", "inst", "examples", "system-monitor-live", script)
  source(path, local = env)
  env
}

monitor_fixture <- function(sequence = 1, source = "test", timestamp = as.numeric(Sys.time())) {
  list(schema_version = 1L, source_id = source, sequence = sequence,
       timestamp = timestamp, collected_at = timestamp,
       metrics = list(cpu = 20, ram = 50, processes = list(list(pid = 1L, name = "R", rss = 1000)), unavailable = list()))
}

test_that("snapshot publication is bounded, versioned and validated", {
  skip_if_not_installed("jsonlite")
  demo <- monitor_demo()
  path <- withr::local_tempdir()
  expect_identical(demo$monitor_read(path)$status, "unavailable")
  writer <- demo$monitor_writer(path, min_interval = 0)
  on.exit(writer$close(), add = TRUE)
  expect_error(demo$monitor_writer(path), "locked")
  for (i in 1:10) {
    expect_true(writer$publish(monitor_fixture(i)))
    reading <- demo$monitor_read(path)
    expect_identical(reading$status, "live")
    expect_equal(reading$snapshot$sequence, i)
  }
  expect_length(demo$monitor_files(path), 3L)
  demo$unlink <- function(...) 1L
  expect_error(writer$publish(monitor_fixture(11)), "Cannot prune")
  expect_length(demo$monitor_files(path), 3L)
  rm("unlink", envir = demo)
  writeLines("partial", file.path(path, ".pending-unfinished"))
  expect_identical(demo$monitor_read(path)$status, "live")
  expect_error(writer$publish(list()), "schema")
  value <- monitor_fixture()
  for (field in c("schema_version", "source_id", "sequence", "timestamp", "metrics")) {
    bad <- value; bad[[field]] <- NULL
    expect_false(demo$monitor_snapshot_valid(bad))
  }
  value$metrics$cpu <- 101
  expect_false(demo$monitor_snapshot_valid(value))
  expect_identical(demo$monitor_read(path, now = as.numeric(Sys.time()) + 20)$status, "stale")
  writeLines("{broken", demo$monitor_files(path)[[1]])
  expect_identical(demo$monitor_read(path)$status, "invalid")
  writer$close(); writer$close()
  expect_error(writer$publish(monitor_fixture()), "closed")
  second <- demo$monitor_writer(path)
  on.exit(second$close(), add = TRUE)
  expect_true(second$publish(monitor_fixture(11)))
  expect_false(second$publish(monitor_fixture(12)))
  expect_equal(demo$monitor_read(path)$snapshot$sequence, 11)
})

test_that("client histories deduplicate, detect loss and recover across restarts", {
  skip_if_not_installed("jsonlite")
  demo <- monitor_demo()
  path <- withr::local_tempdir()
  writer <- demo$monitor_writer(path, min_interval = 0)
  on.exit(writer$close(), add = TRUE)
  client <- demo$monitor_client(path, history = 2L)
  on.exit(client$close(), add = TRUE)
  expect_identical(client$poll()$status, "unavailable")
  writer$publish(monitor_fixture(1))
  expect_identical(client$poll()$status, "live")
  client$poll()
  expect_length(client$stream$history(), 1L)
  writer$publish(monitor_fixture(4))
  expect_equal(client$poll()$missed, 2)
  expect_length(client$stream$history(), 2L)
  expect_identical(client$poll(now = as.numeric(Sys.time()) + 20)$status, "stale")
  writer$publish(monitor_fixture(5))
  expect_identical(client$poll()$status, "live")
  writer$publish(monitor_fixture(2))
  expect_identical(client$poll()$status, "invalid")
  writer$publish(monitor_fixture(1, "restarted"))
  reading <- client$poll()
  expect_identical(reading$status, "live")
  expect_equal(reading$missed, 0)
  expect_length(client$stream$history(), 1L)
  unlink(demo$monitor_files(path))
  expect_identical(client$poll()$status, "unavailable")
  expect_identical(client$poll()$snapshot$source_id, "restarted")
})

test_that("real collector returns structured metrics and supports graceful stop", {
  skip_if_not_installed("jsonlite")
  demo <- monitor_demo("collector.R")
  collect <- demo$monitor_collector("test-real")
  first <- collect()
  expect_true(demo$monitor_snapshot_valid(first))
  expect_null(first$metrics$cpu)
  Sys.sleep(0.05)
  next_value <- collect()
  expect_true(demo$monitor_snapshot_valid(next_value))
  expect_equal(next_value$sequence, 2)
  expect_true(is.null(next_value$metrics$ram) || demo$monitor_number(next_value$metrics$ram, 0, 100))
  expect_true(is.null(next_value$metrics$cpu) || demo$monitor_number(next_value$metrics$cpu, 0, 100))
  path <- withr::local_tempdir()
  expect_equal(demo$run_collector(path, interval = 0.05, max_samples = 2), 2)
  expect_equal(demo$monitor_read(path)$snapshot$sequence, 2)
  expect_false(dir.exists(file.path(path, ".writer-lock")))
  file.create(file.path(path, "STOP"))
  expect_equal(demo$run_collector(path, interval = 0.05, max_samples = 2), 0)
})

test_that("TUI independently polls live and stale data without owning collector", {
  skip_if_not_installed("jsonlite")
  demo <- monitor_demo("tui.R")
  path <- withr::local_tempdir()
  writer <- demo$monitor_writer(path, min_interval = 0)
  on.exit(writer$close(), add = TRUE)
  writer$publish(monitor_fixture())
  ui <- demo$monitor_tui(path, stale_after = 1)
  pilot <- test_app(ui$app, 100, 18)
  on.exit({ pilot$stop(); ui$close() }, add = TRUE)
  pilot$advance(1.1)
  expect_match(pilot$query_one("#source")$text, "Source: live")
  expect_match(pilot$query_one("#metrics")$text, "CPU: 20.0% RAM: 50.0%", fixed = TRUE)
  writer$publish(monitor_fixture(2, timestamp = as.numeric(Sys.time()) - 10))
  pilot$advance(1.1)
  expect_match(pilot$query_one("#source")$text, "Source: stale")
  pilot$press("q")
  ui$close()
  expect_true(ui$client$stream$is_closed())
  expect_true(writer$publish(monitor_fixture(3)))
  again <- demo$monitor_tui(path)
  second <- test_app(again$app, 100, 18)
  on.exit({ second$stop(); again$close() }, add = TRUE)
  second$advance(1.1)
  expect_match(second$query_one("#source")$text, "Source: live")
})

test_that("Shiny server polls real snapshots and recovers without collector ownership", {
  skip_if_not_installed("jsonlite")
  skip_if_not_installed("shiny")
  demo <- monitor_demo("shiny-app.R")
  path <- withr::local_tempdir()
  writer <- demo$monitor_writer(path, min_interval = 0)
  on.exit(writer$close(), add = TRUE)
  shiny::testServer(demo$monitor_server(path, stale_after = 1), {
    session$flushReact()
    expect_identical(current()$status, "unavailable")
    collect <- demo$monitor_collector("shiny-real")
    writer$publish(collect())
    session$elapse(600)
    expect_identical(current()$status, "live")
    expect_match(output$metrics, "RAM:")
    expect_true(is.list(output$history))
    old <- collect(); old$timestamp <- as.numeric(Sys.time()) - 10
    writer$publish(old)
    session$elapse(600)
    expect_identical(current()$status, "stale")
    writer$publish(collect())
    session$elapse(600)
    expect_identical(current()$status, "live")
    expect_length(client$stream$history(), 3L)
    session$close()
    expect_true(client$stream$is_closed())
  })
  # A second Shiny session can read the still-running writer independently.
  writer$publish(monitor_fixture(1, "new-source"))
  shiny::testServer(demo$monitor_server(path), {
    session$flushReact()
    expect_identical(current()$status, "live")
    expect_length(client$stream$history(), 1L)
  })
})
