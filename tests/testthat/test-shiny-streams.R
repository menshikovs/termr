test_that("one Shiny binding serves latest/history/status and coalesces bursts", {
  skip_if_not_installed("shiny")
  source <- termr_stream("metrics")
  receiver <- termr_shiny_receiver(source, max_points = 10L)
  on.exit(receiver$close(), add = TRUE)
  shiny::testServer(function(input, output, session) {
    latest <- termr_shiny_reactive(receiver, session)
    history <- termr_shiny_history(receiver, session, max_points = 10L)
    status <- termr_shiny_status(receiver, session)
  }, {
    session$flushReact()
    expect_null(latest())
    expect_identical(status()$state, "unavailable")
    expect_identical(receiver$diagnostics()$sessions, 1L)
    expect_identical(source$subscriber_count(), 1L)
    for (i in 1:1000) source$emit(list(timestamp = as.numeric(Sys.time()), cpu = i, ram = 50))
    receiver$poll(); session$flushReact()
    expect_equal(latest()$cpu, 1000)
    expect_length(history(), 10L)
    expect_identical(vapply(history(), function(x) x$payload$cpu, 0L), 991:1000)
    expect_gte(receiver$diagnostics()$coalesced, 999)
    expect_identical(status()$state, "live")
    before <- receiver$diagnostics()$processed
    receiver$poll(); session$flushReact()
    expect_equal(receiver$diagnostics()$processed, before)
    session$close()
    expect_identical(receiver$diagnostics()$sessions, 0L)
    expect_false(receiver$is_closed())
    expect_false(source$is_closed())
  })
  receiver$close()
  expect_identical(source$subscriber_count(), 0L)
})

test_that("receiver history deduplicates and resets identity without replaying lost points", {
  skip_if_not_installed("shiny")
  source <- termr_stream("metrics")
  receiver <- termr_shiny_receiver(source, max_points = 3L,
    validate = function(x) is.list(x) && is.numeric(x$cpu))
  on.exit(receiver$close(), add = TRUE)
  emit <- function(id, seq, timestamp = as.numeric(Sys.time())) {
    source$emit(list(source_id = id, sequence = seq, timestamp = timestamp, cpu = seq))
    receiver$poll()
  }
  emit("a", 1); emit("a", 1); emit("a", 0); emit("a", 4)
  expect_length(receiver$history(), 2L)
  expect_equal(receiver$status()$gaps, 2)
  expect_equal(receiver$diagnostics()$duplicates, 1)
  expect_equal(receiver$diagnostics()$out_of_order, 1)
  emit("a", 5, "bad")
  expect_identical(receiver$status()$state, "invalid")
  expect_equal(receiver$latest()$cpu, 4)
  emit("a", 5)
  expect_identical(receiver$status()$state, "live")
  emit("b", 1)
  expect_length(receiver$history(), 1L)
  expect_equal(receiver$status()$generation, 2)
  expect_equal(termr_stream_data(receiver, fields = "cpu")$cpu, 1)
  emit("b", 2, as.numeric(Sys.time()) - 20)
  expect_identical(receiver$status()$state, "stale")
  receiver$close(); receiver$close()
  expect_identical(receiver$status()$state, "closed")
})

test_that("shared receiver leases survive individual sessions and release all observers", {
  skip_if_not_installed("shiny")
  source <- termr_stream("metrics")
  receiver <- termr_shiny_receiver(source, close_source = TRUE)
  on.exit(receiver$close(), add = TRUE)
  sessions <- lapply(1:20, function(i) shiny::MockShinySession$new())
  on.exit(for (s in sessions) s$close(), add = TRUE)
  values <- lapply(sessions, function(s) {
    termr_shiny_history(receiver, s)
    termr_shiny_status(receiver, s)
    termr_shiny_reactive(receiver, s)
  })
  expect_identical(receiver$diagnostics()$sessions, 20L)
  expect_identical(receiver$diagnostics()$observers, 1L)
  expect_identical(source$subscriber_count(), 1L)
  source$emit(list(timestamp = Sys.time(), cpu = 42))
  receiver$poll()
  expect_true(all(vapply(values, function(v) identical(shiny::isolate(v())$cpu, 42), logical(1))))
  for (s in sessions[1:5]) s$close()
  expect_identical(receiver$diagnostics()$sessions, 15L)
  expect_false(source$is_closed())
  for (s in sessions) s$close()
  expect_identical(receiver$diagnostics()$sessions, 0L)
  receiver$close()
  expect_identical(receiver$diagnostics()$observers, 0L)
  expect_true(source$is_closed())
})

test_that("implicit session receivers detach without closing a caller-owned source", {
  skip_if_not_installed("shiny")
  source <- termr_stream("metrics")
  session <- shiny::MockShinySession$new()
  on.exit(session$close(), add = TRUE)
  termr_shiny_status(source, session)
  termr_shiny_reactive(source, session)
  termr_shiny_history(source, session)
  expect_identical(source$subscriber_count(), 1L)
  session$close()
  expect_identical(source$subscriber_count(), 0L)
  expect_false(source$is_closed())
  expect_error(termr_shiny_reactive(source, session = NULL), "session")
  expect_error(termr_shiny_reactive(source, session), "closed")
})

test_that("an empty snapshot from a new source clears old current data", {
  skip_if_not_installed("shiny")
  source <- termr_stream("metrics")
  remote <- new.env()
  remote$state <- list(state = "live", source_id = "one", sequence = 1)
  handle <- c(source, list(status = function() remote$state))
  receiver <- termr_shiny_receiver(handle)
  on.exit(receiver$close(), add = TRUE)
  source$emit(list(timestamp = Sys.time(), cpu = 42))
  receiver$poll()
  expect_equal(receiver$latest()$cpu, 42)
  source$clear()
  remote$state <- list(state = "live", source_id = "two", sequence = 0)
  receiver$poll()
  expect_null(receiver$latest())
  expect_length(receiver$history(), 0L)
  expect_identical(receiver$status()$state, "unavailable")
  expect_equal(receiver$status()$generation, 2)
})
