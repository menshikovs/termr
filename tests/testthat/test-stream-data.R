test_that("stream data frames keep stable types, missing values and UTC times", {
  empty <- termr_stream_data(list(), c("cpu", "ram"))
  expect_s3_class(empty, "data.frame")
  expect_s3_class(empty$timestamp, "POSIXct")
  expect_type(empty$cpu, "double")
  expect_type(empty$source_id, "character")
  expect_type(empty$sequence, "double")
  expect_type(empty$gap, "logical")
  expect_type(empty$segment, "integer")
  expect_equal(nrow(empty), 0)
  t <- as.POSIXct("2026-01-01", tz = "UTC")
  rows <- list(list(timestamp = t, cpu = 10L, ram = NULL),
    list(timestamp = as.numeric(t) + 1, cpu = NA_real_, ram = 50),
    list(timestamp = "bad", cpu = Inf, ram = NaN),
    list(timestamp = as.numeric(t) + 3, cpu = "42", ram = 60))
  df <- termr_stream_data(rows)
  expect_identical(df$cpu, c(10, NA_real_, NA_real_, NA_real_))
  expect_identical(df$ram, c(NA_real_, 50, NA_real_, 60))
  expect_true(is.na(df$timestamp[[3]]))
  expect_identical(attr(df$timestamp, "tzone"), "UTC")
  expect_equal(nrow(termr_stream_data(rows, max_points = 2)), 2)
  expect_equal(nrow(termr_stream_data(rows, max_points = 0)), 0)
  missing <- termr_stream_data(list(NULL))
  expect_true(is.na(missing$cpu[[1L]]))
  expect_true(is.na(missing$timestamp[[1L]]))
})

test_that("stream data marks source, time and sequence discontinuities", {
  rows <- lapply(seq_len(6), function(i) list(timestamp = i, cpu = i, ram = 10,
    source_id = if (i < 5) "a" else "b", sequence = c(1, 2, 4, 3, 1, 2)[[i]]))
  df <- termr_stream_data(rows)
  expect_identical(df$gap, c(FALSE, FALSE, TRUE, TRUE, FALSE, FALSE))
  expect_identical(df$segment, c(1L, 1L, 2L, 3L, 4L, 4L))
  x <- termr_stream(history = 3L)
  for (row in rows) x$emit(row)
  expect_identical(termr_stream_data(x)$cpu, c(4, 5, 6))
  x$close()
  nested <- list(list(collected = 1, metrics = list(cpu = 20)))
  df <- termr_stream_data(nested, fields = "cpu", extractor = function(x) list(timestamp = x$collected, cpu = x$metrics$cpu))
  expect_identical(df$cpu, 20)
  expect_error(termr_stream_data(nested, extractor = function(x) 1), "named list")
  expect_error(termr_stream_data(list(), fields = c("timestamp", "cpu")), "fields")
  expect_error(termr_stream_data(list(), max_points = -1), "max_points")
})
